在KTP项目中，Vplan主要包含一下内容：
（一） Overview
   1. 参考依据：总体设计方案、详细设计方案、寄存器手册、端口信号列表
   2. 选用的验证方法学：UVM，随机或者直接验证，FPGA原型验证
   3. 入口标准：RTL代码完成入库，给出tag编号；设计文档完成，文档入库；UT验证单元代码通过工具检查；UT验证策略完成评审
   4. 完成标准
      (1) 	完成feature、测试点文档以及波形检视质量活动。
      (2)	定义的功能覆盖率达到100%；
      (3)	行覆盖率达到100%，条件覆盖率达到100%，状态机覆盖率达到100%、toggle覆盖率达到100%；对未达到覆盖率要求的，说明未覆盖的原因，并给出详细分析报告；
      (4)	UT的问题单均已关闭；
      (5)	完成UT验证报告。

(二) DUV描述
     验证对设计的反串讲，从一个整体的角度看设计，端到端。定义清楚DUV，但不用详细描述DUV功能。
  1. 验证对象的时钟和复位策略
  2. 接口、功能；在这个项目中主要包含支持的AXI4传输特性、APB配置接口与中断
  3. 功能关注点
  4. DUT低功耗与应用场景
  5. 性能关注：输入到有效输出的latency，吞吐率，带宽，无气泡
  6. 维测关注；挂死时能否完成问题定位

