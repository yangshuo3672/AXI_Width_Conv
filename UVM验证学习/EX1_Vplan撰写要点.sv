     挖掘总线相关验证的典型问题，挖掘背后根因，提供验证思路
     （1）反压验证：充分验证下游的各种反压情况，反压组合
     （2）上游strobe，narrow操作类型组合，遍历各种传输类型
  3. 测试点规划
