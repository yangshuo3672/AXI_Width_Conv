冗余度级别	  数值	 说明
UVM_NONE	   0	   永不屏蔽：无论全局阈值如何设置，该消息始终会被打印。
UVM_LOW	    100	   最关键信息：打印测试环境的启动/结束、关键配置等最重要的概要信息。
UVM_MEDIUM	200	   默认级别：打印常规的流程和状态转换信息，是仿真时最常用的级别。
UVM_HIGH	  300	   详细调试信息：打印事务处理细节、数据包内容等模块级调试信息。
UVM_FULL	  400	   非常详细的信息：打印循环内迭代、临时变量值等，用于深度定位问题。
UVM_DEBUG	  500	   最详尽调试信息：打印所有辅助性调试输出，用于追踪最复杂的内部逻辑。

只有消息的荣誉级别小于或等于当前设置的阈值时，才会被打印。

全局控制：
# 两种写法等价
+UVM_VERBOSITY=UVM_HIGH
+UVM_VERBOSITY=HIGH
